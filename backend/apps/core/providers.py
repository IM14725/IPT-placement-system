"""Provider adapters (mock-first).

SMS goes through AstraCall (https://astracall.cc/api/v1); email through Django's mail backend. In dev
and tests both log to the console.
"""

import uuid

import requests
from django.conf import settings
from django.core.mail import EmailMessage

SMS_TIMEOUT_SECONDS = 15
ASTRACALL_DEFAULT_URL = "https://astracall.cc/api/v1"


class SmsDeliveryError(Exception):
    """The SMS provider refused or could not be reached. The message never holds the SMS text."""


def sms_is_mock() -> bool:
    """``SMS_BACKEND``: "mock" forces the console adapter, "astracall" the real one, "auto" uses
    AstraCall only when ``ASTRACALL_API_KEY`` is set."""
    backend = getattr(settings, "SMS_BACKEND", "auto")
    if backend == "mock":
        return True
    if backend == "astracall":
        return False
    return not getattr(settings, "ASTRACALL_API_KEY", "")


def _international(phone: str) -> str:
    """AstraCall wants +255XXXXXXXXX. We store 2557XXXXXXXX (digits only); 07XXXXXXXX is also accepted."""
    digits = "".join(ch for ch in (phone or "") if ch.isdigit())
    if digits.startswith("0"):
        digits = "255" + digits[1:]
    return "+" + digits


def _astracall_error(response) -> str:
    """``HTTP 422 invalid_recipient: ...`` from the provider's error body. Never includes our request."""
    try:
        err = (response.json() or {}).get("error") or {}
    except ValueError:
        err = {}
    code = str(err.get("code") or "error")
    message = str(err.get("message") or "")[:120]
    return f"AstraCall HTTP {response.status_code} {code}: {message}".rstrip(": ")


def send_sms(phone: str, text: str, *, kind: str = "transactional", idempotency_key: str | None = None) -> dict:
    """Send one SMS. ``kind`` is "otp" (code generated by us, POST /sms/otp) or "transactional" (POST /sms/send).

    AstraCall answers 202 = accepted, not delivered. A timeout or a 503 ``submission_unknown`` may mean the
    message already went out, so the one retry reuses the SAME Idempotency-Key and can never double-send.
    """
    if sms_is_mock():
        print(f"[SMS:MOCK] -> {phone}: {text}")
        return {"status": "SENT", "provider": "mock-sms", "phone": phone}

    api_key = getattr(settings, "ASTRACALL_API_KEY", "")
    if not api_key:
        raise SmsDeliveryError("SMS_BACKEND is 'astracall' but ASTRACALL_API_KEY is not set")

    base = (getattr(settings, "ASTRACALL_BASE_URL", "") or ASTRACALL_DEFAULT_URL).rstrip("/")
    key = idempotency_key or str(uuid.uuid4())
    payload = {
        "to": _international(phone),
        "sender_id": getattr(settings, "ASTRACALL_SENDER_ID", "") or "POSTSMS",
        "message": text,
        "reference": key[:64],
    }
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
        "Idempotency-Key": key,
    }
    url = f"{base}/sms/otp" if kind == "otp" else f"{base}/sms/send"

    response = None
    for attempt in (1, 2):
        try:
            response = requests.post(url, json=payload, headers=headers, timeout=SMS_TIMEOUT_SECONDS)
        except requests.RequestException as exc:
            if attempt == 2:
                raise SmsDeliveryError(f"AstraCall unreachable: {type(exc).__name__}") from exc
            continue
        if response.status_code == 503 and attempt == 1:
            continue
        break
    if response.status_code >= 400:
        raise SmsDeliveryError(_astracall_error(response))
    try:
        data = (response.json() or {}).get("data") or {}
    except ValueError:
        data = {}
    return {
        "status": "SENT",  # accepted, not necessarily delivered yet
        "provider": "astracall-sms",
        "phone": phone,
        "message_id": data.get("id"),
        "response": data,
    }


class _BrandedEmail:
    """Mixin for ``EmailMultiAlternatives``: puts the logo inside the HTML part as an inline ``cid:`` image
    (multipart/related), the layout Gmail, Outlook and phone clients all render without a download prompt."""

    logo: bytes | None = None
    logo_cid = "ipt-logo"
    inline_images: dict | None = None  # {content id: PNG bytes}, e.g. a receipt's QR code

    def message(self, *, policy=None):
        msg = super().message(**({"policy": policy} if policy is not None else {}))
        if self.logo or self.inline_images:
            html_part = msg.get_body(preferencelist=("html",))
            if html_part is not None:
                if self.logo:
                    html_part.add_related(
                        self.logo, "image", "png", cid=f"<{self.logo_cid}>", disposition="inline"
                    )
                # Independent of the logo: a hosted EMAIL_LOGO_URL means no logo part, but the QR still travels.
                for cid, data in (self.inline_images or {}).items():
                    html_part.add_related(data, "image", "png", cid=f"<{cid}>", disposition="inline")
        return msg


def send_email(
    subject: str,
    to: list,
    body: str,
    attachments=None,
    *,
    html: bool = True,
    html_content: str | None = None,
    inline_images: dict | None = None,
) -> dict:
    """Send an email. ``body`` is plain text; it is also sent as a branded HTML part (logo, platform
    colours, OTP code box) unless ``html=False``. A problem building the HTML never blocks the email."""
    from django.core.mail import EmailMultiAlternatives

    class Branded(_BrandedEmail, EmailMultiAlternatives):
        pass

    from_email = getattr(settings, "DEFAULT_FROM_EMAIL", "noreply@iptmarketplace.com")
    email = Branded(
        subject=subject,
        body=body,
        to=to,
        from_email=from_email,
    )

    if html:
        try:
            from apps.core import email_layout

            # ``html_content`` is a finished page from a caller with its own layout (the receipt).
            page = html_content or email_layout.render_email_html(subject, body)
            email.attach_alternative(page, "text/html")
            if f"cid:{email_layout.LOGO_CID}" in page:
                email.logo = email_layout.logo_bytes()
                email.logo_cid = email_layout.LOGO_CID
            email.inline_images = {cid: data for cid, data in (inline_images or {}).items() if f"cid:{cid}" in page}
        except Exception:  # noqa: BLE001 - the plain-text email must still go out
            import logging

            logging.getLogger(__name__).warning("Branded HTML email could not be built; sending plain text", exc_info=True)
            email.alternatives = []
            email.logo = None
            email.inline_images = None

    if attachments:
        for attachment in attachments:
            if isinstance(attachment, str):
                email.attach_file(attachment)
            elif isinstance(attachment, dict):
                email.attach(
                    attachment.get("filename", "attachment"),
                    attachment.get("content", b""),
                    attachment.get("mimetype")
                )

    email.send(fail_silently=False)
    
    # If the default backend is the console, log it so dev knows it was mocked
    provider = "smtp" if "smtp" in getattr(settings, "EMAIL_BACKEND", "") else "mock-email"
    if provider == "mock-email":
        print(f"[EMAIL:MOCK] -> {', '.join(to)} | {subject} (Attachments: {len(attachments or [])})")
        
    return {"status": "SENT", "provider": provider}