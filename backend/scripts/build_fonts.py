"""Self-host the web fonts (Inter + a Material Symbols subset).

Why: the page used to load ~1.2 MB of icon font plus two Google stylesheets from third-party
hosts, which dominated load time on slow mobile networks. This script downloads the fonts once,
subsets the icon font to only the icons the project actually references, and writes
``static/fonts/*.woff2`` plus ``static/css/fonts.css``. The generated files are committed, so the
app runs without Internet access or a build step. Re-run after adding a new icon name:

    python scripts/build_fonts.py            # from backend/

It needs Internet access (fonts.googleapis.com, raw.githubusercontent.com) only when it runs.
"""
from __future__ import annotations

import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
FONT_DIR = BACKEND / "static" / "fonts"
CSS_OUT = BACKEND / "static" / "css" / "fonts.css"

# A modern browser UA makes Google return woff2 files (and unicode-range split faces).
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36"
CODEPOINTS_URL = (
    "https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/"
    "MaterialSymbolsOutlined%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints"
)
# Where icon names can appear: templates, JS, and Python (icon names chosen in views/dashboards).
SCAN = [
    (BACKEND / "templates", ("*.html", "*.txt")),
    (BACKEND / "static" / "js", ("*.js",)),
    (BACKEND / "apps", ("*.py",)),
    (BACKEND.parent / "realtime", ("*.py",)),
]
# Icons that are only chosen dynamically and might not appear as a literal token.
EXTRA_ICONS = {"contrast", "light_mode", "dark_mode", "menu", "close", "check_circle", "error", "info", "warning"}


def fetch(url: str, binary: bool = False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as resp:  # noqa: S310 - fixed https URLs
        data = resp.read()
    return data if binary else data.decode("utf-8")


def known_icon_names() -> set[str]:
    return {line.split()[0] for line in fetch(CODEPOINTS_URL).splitlines() if line.strip()}


def used_icon_names(known: set[str]) -> list[str]:
    tokens: set[str] = set()
    token_re = re.compile(r"[a-z][a-z0-9_]*")
    for root, patterns in SCAN:
        for pattern in patterns:
            for path in root.rglob(pattern):
                if ".venv" in path.parts or "migrations" in path.parts or "__pycache__" in path.parts:
                    continue
                try:
                    text = path.read_text(encoding="utf-8", errors="ignore")
                except OSError:
                    continue
                tokens.update(token_re.findall(text))
    names = (tokens & known) | (EXTRA_ICONS & known)
    return sorted(names)


def faces(css: str) -> list[tuple[str, str]]:
    """Return [(subset_comment, block)] for each @font-face in a Google CSS response."""
    out = []
    for m in re.finditer(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S):
        out.append((m.group(1), m.group(2)))
    if not out:  # single face, no subset comments (icon_names responses)
        out = [("all", m.group(0)) for m in re.finditer(r"@font-face\s*\{.*?\}", css, re.S)]
    return out


def download_face(block: str, filename: str) -> str:
    url = re.search(r"url\((https://[^)]+)\)", block).group(1)
    (FONT_DIR / filename).write_bytes(fetch(url, binary=True))
    return re.sub(r"src:[^;]+;", f"src: url('../fonts/{filename}') format('woff2');", block)


def main() -> int:
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    chunks = ["/* GENERATED by scripts/build_fonts.py - do not edit by hand. */\n"]

    # --- Inter (variable weight), latin + latin-ext only (English + Kiswahili) ---
    inter_css = fetch("https://fonts.googleapis.com/css2?family=Inter:wght@100..900&display=swap")
    for subset, block in faces(inter_css):
        if subset not in ("latin", "latin-ext"):
            continue
        out = download_face(block, f"inter-{subset}.woff2")
        out = re.sub(r"font-display:\s*\w+", "font-display: swap", out)
        chunks.append(out + "\n")

    # --- Material Symbols Outlined, subset by icon name, FILL axis kept (0..1) ---
    names = used_icon_names(known_icon_names())
    print(f"{len(names)} icon names found")
    # Committed next to the font so a test can verify every icon used in the templates is in the subset.
    (FONT_DIR / "material-symbols-icons.txt").write_text("\n".join(names) + "\n", encoding="utf-8")
    q = urllib.parse.urlencode(
        {"family": "Material Symbols Outlined:FILL@0..1", "icon_names": ",".join(names), "display": "block"},
        quote_via=urllib.parse.quote,
    )
    icon_css = fetch("https://fonts.googleapis.com/css2?" + q)
    icon_faces = faces(icon_css)
    if not icon_faces:
        print("No icon font-face returned", file=sys.stderr)
        return 1
    out = download_face(icon_faces[0][1], "material-symbols-outlined.woff2")
    out = re.sub(r"font-display:\s*\w+", "font-display: block", out)
    chunks.append(out + "\n")
    chunks.append(
        """
/* The Google API normally injects this class; self-hosting means we define it. The fixed box and
   overflow clip keep the layout stable (and hide the ligature text) until the icon font is ready. */
.material-symbols-outlined {
  font-family: 'Material Symbols Outlined';
  font-weight: normal; font-style: normal; font-size: 24px; line-height: 1;
  letter-spacing: normal; text-transform: none; display: inline-block; white-space: nowrap;
  word-wrap: normal; direction: ltr; font-feature-settings: 'liga'; -webkit-font-feature-settings: 'liga';
  -webkit-font-smoothing: antialiased; text-rendering: optimizeLegibility;
  width: 1em; height: 1em; overflow: hidden; flex-shrink: 0;
}
"""
    )
    CSS_OUT.write_text("".join(chunks), encoding="utf-8")
    for f in sorted(FONT_DIR.glob("*.woff2")):
        print(f"{f.name}: {f.stat().st_size / 1024:.1f} kB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
